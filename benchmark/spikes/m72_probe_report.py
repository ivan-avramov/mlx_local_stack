#!/usr/bin/env python3
"""Generate benchmark/results/m72/PROBE.md from the m72_tq4_probe JSONs (never hand-edit the output).

Three parts: (1) per-layer kernel tables (NAX on, two passes; NAX off); (2) instrument validation against the P475
matrix of Qwen3.8-27B-mlx-uniform-4bit (same attention shapes); (3) projections for
Qwen3.8-27B-Fable-Distill-OptiQ-4.5bpw-mixed from its recorded shipped-state numbers (native16 + fused_v1 + joint_v1).
Usage: python benchmark/spikes/m72_probe_report.py <probe_dir> > benchmark/results/m72/PROBE.md
"""

import json
import sys
from pathlib import Path

LAYERS = 16
CHUNK = 512
VERIFY_K = "3"  # drafter block_size 3 -> verify blocks of 3 queries

# P475 matrix means (b1, b2), benchmark/results/p475/MATRIX.Qwen3.8-27B-mlx-uniform-4bit.md (a4ef6f96)
P475 = {
    "rungs": [8192, 131072, 196608, 260096],
    "prefill_tps": {"N16": [923.86, 463.10, 338.57, 275.66], "TQ4": [802.71, 226.49, 160.98, 128.83]},
    "decode_tps": {"N16": [57.59, 24.51, 19.47, 15.03], "TQ4": [51.59, 19.72, 14.75, 12.72],
                   "TQ4-OFF": [27.88, 16.83, 13.68, 11.64]},
    "acceptance": {"N16": [0.8041, 0.7163, 0.8041, 0.7817], "TQ4": [0.8316, 0.7949, 0.7525, 0.8316]},
}
# Qwen3.8-27B-Fable-Distill-OptiQ-4.5bpw-mixed, shipped state
PICK_BASELINE = {
    # cold prefill seconds: 128K M57 arm E (fused_v1 + lazy embeddings, 2026-10-05); 260096 tokens P426 M1 ON 383.5 tok/s
    "prefill_s": {131072: 294.0, 260096: 260096 / 383.5},
    # decode tok/s MTP ON (joint_v1): M58 arm B 128K mean 24.8, P426 M1 ON 256K 16.03; MTP OFF P426 M1 13.39 at 256K
    "decode_on_tps": {131072: 24.8, 260096: 16.03},
    "decode_off_tps": {260096: 13.39},
    "emitted_per_round": 2.35,  # M58 mechanism session, 128K
}


def load(d):
    out = {}
    for name in ("probe-nax-on-1", "probe-nax-on-2", "probe-nax-off"):
        p = Path(d) / f"{name}.json"
        if p.exists():
            out[name] = json.loads(p.read_text())
    return out


def ck(run):
    return {c["T"]: c for c in run["checkpoints"]}


def median_of(x):
    return x["median_ms"]


def mean_on(runs, getter):
    """Mean of the two NAX-on passes (or the one present)."""
    vals = [getter(ck(runs[n])) for n in ("probe-nax-on-1", "probe-nax-on-2") if n in runs]
    return sum(vals) / len(vals)


def interp(points, T):
    """Piecewise-linear in T through (T_i, v_i); linear extrapolation below the first segment."""
    pts = sorted(points.items())
    if T <= pts[0][0]:
        (t0, v0), (t1, v1) = pts[0], pts[1]
    else:
        seg = next(((a, b) for a, b in zip(pts, pts[1:]) if a[0] <= T <= b[0]), (pts[-2], pts[-1]))
        (t0, v0), (t1, v1) = seg
    return max(0.0, v0 + (v1 - v0) * (T - t0) / (t1 - t0))


def prefill_attn_total_s(points_ms, N):
    """Seconds of attention over a cold N-token prefill: LAYERS x sum over chunks of the chunk cost at its end key."""
    return LAYERS * sum(interp(points_ms, j * CHUNK) for j in range(1, N // CHUNK + 1)) / 1e3


def fmt(x, nd=2):
    return "—" if x is None else f"{x:.{nd}f}"


def main():
    runs = load(sys.argv[1])
    on_names = [n for n in ("probe-nax-on-1", "probe-nax-on-2") if n in runs]
    Ts = sorted(ck(runs[on_names[0]]))
    # Projections / validation interpolate over sub-cap checkpoints only: at exactly the cap the state is contiguous
    # (no layout copy), which a served prompt never sees.
    Tp = [T for T in Ts if T < 262144]
    g = lambda f: {T: mean_on(runs, lambda c, T=T: f(c[T])) for T in Tp}
    P = print
    P("# M72 step 1.1 — TQ4 vs native16 attention probe (GENERATED by `benchmark/spikes/m72_probe_report.py`; never hand-edit)\n")
    m = runs[on_names[0]]["meta"]
    P(f"MLX {m['mlx']}, {m['device']['device_name']} `{m['device']['architecture']}`; per full-attention layer; 24 q / 4 kv "
      f"heads, head dim 256, bf16; synthetic K/V; medians of timed iterations. Passes: {', '.join(runs)}. "
      f"NAX-on values are the mean of {len(on_names)} pass(es).\n")

    # ---------- 1. kernel tables ----------
    P("## 1. Per-layer kernel times (ms), NAX on\n")
    P("### Decode (one query)\n")
    P("Production = the shipped layout (below the cap, a time-slice of the full-cap preallocated buffer); contiguous = the same "
      "bytes copied contiguous first (isolates the layout's cost). Split kernels are timed one by one (each with its own sync).\n")
    P("| T | native16 SDPA | TQ4 production | TQ4 contiguous | TQ4 legacy | split prod: prep / pass1 / pass2 / rot | pass1 contiguous | read TQ4 bytes | read native16 bytes | eff. GB/s n16 / TQ4 / TQ4 contig / TQ4-read |")
    P("|---|---|---|---|---|---|---|---|---|---|")
    for T in Ts:
        f = lambda key: mean_on(runs, lambda c: median_of(c[T]["decode"][key]))
        sp = lambda key: mean_on(runs, lambda c: median_of(c[T]["decode"]["tq4_split"][key]))
        c0 = ck(runs[on_names[0]])[T]
        b_tq, b_n = c0["bytes"]["tq4_kv"], c0["bytes"]["native16_kv"]
        p1c = mean_on(runs, lambda c: median_of(c[T]["decode"]["tq4_split_contiguous"]["pass1"]))
        P(f"| {T} | {f('native16'):.3f} | {f('tq4'):.3f} | {f('tq4_contiguous'):.3f} | {f('tq4_legacy'):.3f} | "
          f"{sp('prepare_queries'):.3f} / {sp('pass1'):.3f} / {sp('pass2'):.3f} / {sp('rotate_inverse'):.3f} | {p1c:.3f} | "
          f"{f('read_tq4_bytes'):.3f} | {f('read_native16_bytes'):.3f} | {b_n / f('native16') / 1e6:.0f} / "
          f"{b_tq / f('tq4') / 1e6:.0f} / {b_tq / f('tq4_contiguous') / 1e6:.0f} / {b_tq / f('read_tq4_bytes') / 1e6:.0f} |")
    P("\n### MTP verify block (ms per block per layer)\n")
    P("| T | k | native16 joint | native16 per-query | TQ4 per-query (shipped) | TQ4 per-query, contiguous parent | TQ4 per-query / TQ4 single decode |")
    P("|---|---|---|---|---|---|---|")
    for T in Ts:
        dec = mean_on(runs, lambda c: median_of(c[T]["decode"]["tq4"]))
        for k in ck(runs[on_names[0]])[T]["verify"]:
            v = lambda key: mean_on(runs, lambda c: median_of(c[T]["verify"][k][key]))
            P(f"| {T} | {k} | {v('native16_joint'):.3f} | {v('native16_per_query'):.3f} | {v('tq4_per_query'):.3f} | "
              f"{v('tq4_per_query_contiguous_parent'):.3f} | {v('tq4_per_query') / dec:.2f}× |")
    P("\n### Prefill chunk (512 queries ending at key T, causal; ms per chunk per layer)\n")
    P("| T | native16 auto | native16 fused_v1 | TQ4 production (loop) | TQ4 decomposed | TQ4 dequant only | TQ4 dequant + fused SDPA | TQ4 rotated-space dequant only | TQ4 rotated-space dequant + fused SDPA | KV append 512 tok TQ4 / n16 |")
    P("|---|---|---|---|---|---|---|---|---|---|")
    for T in Ts:
        p = lambda key: mean_on(runs, lambda c: median_of(c[T]["prefill_chunk"][key]))
        dc = ck(runs[on_names[0]])[T]["prefill_chunk"]["tq4_decomposed"]
        dcv = fmt(mean_on(runs, lambda c: median_of(c[T]["prefill_chunk"]["tq4_decomposed"])), 1) if "median_ms" in dc else "skipped (memory)"
        ap = lambda key: mean_on(runs, lambda c: c[T]["kv_append_chunk_ms"][key])
        P(f"| {T} | {p('native16_auto'):.1f} | {p('native16_fused_v1'):.1f} | {p('tq4_production'):.1f} | {dcv} | "
          f"{p('tq4_dequant_only'):.1f} | {p('tq4_dequant_fused_sdpa'):.1f} | {p('tq4_dequant_rotated_only'):.1f} | "
          f"{p('tq4_rotated_dequant_fused_sdpa'):.1f} | {ap('tq4_mean_last64'):.2f} / {ap('native16_mean_last64'):.2f} |")
    P("\n### Instrument checks\n")
    for T in Ts:
        c = ck(runs[on_names[0]])[T]
        P(f"- T={T}: decode split vs production max-abs {c['decode']['split_vs_production']['max_abs']:.2e}; prefill "
          f"dequant+fused vs production rel {c['prefill_chunk']['dequant_fused_vs_production']['rel_to_max']:.2e}; "
          f"rotated+fused vs production rel {c['prefill_chunk']['rotated_fused_vs_production']['rel_to_max']:.2e}"
          + (f"; decomposed vs production rel {c['prefill_chunk']['decomposed_vs_production']['rel_to_max']:.2e}"
             if "decomposed_vs_production" in c["prefill_chunk"] else "")
          + f"; peak {c['peak_GB']:.1f} GB; power {c['power']}")
    if len(on_names) == 2:
        P("\nPass-to-pass drift (on-2 / on-1, decode TQ4 and prefill TQ4 production): " + ", ".join(
            f"T={T} {median_of(ck(runs[on_names[1]])[T]['decode']['tq4']) / median_of(ck(runs[on_names[0]])[T]['decode']['tq4']):.3f} / "
            f"{median_of(ck(runs[on_names[1]])[T]['prefill_chunk']['tq4_production']) / median_of(ck(runs[on_names[0]])[T]['prefill_chunk']['tq4_production']):.3f}"
            for T in Ts))

    # ---------- NAX control ----------
    if "probe-nax-off" in runs:
        off = ck(runs["probe-nax-off"])
        P("\n## 2. Neural Accelerator control (`MLX_METAL_GPU_ARCH=applegpu_g16s`): NAX-off / NAX-on time ratio\n")
        P("A ratio ≈ 1.00 means the path does not use the accelerators.\n")
        rows = [("decode native16", lambda c: median_of(c["decode"]["native16"])),
                ("decode TQ4", lambda c: median_of(c["decode"]["tq4"])),
                (f"verify k={VERIFY_K} native16 joint", lambda c: median_of(c["verify"][VERIFY_K]["native16_joint"])),
                (f"verify k={VERIFY_K} TQ4 per-query", lambda c: median_of(c["verify"][VERIFY_K]["tq4_per_query"])),
                ("prefill native16 auto", lambda c: median_of(c["prefill_chunk"]["native16_auto"])),
                ("prefill native16 fused_v1", lambda c: median_of(c["prefill_chunk"]["native16_fused_v1"])),
                ("prefill TQ4 production", lambda c: median_of(c["prefill_chunk"]["tq4_production"])),
                ("prefill TQ4 dequant + fused", lambda c: median_of(c["prefill_chunk"]["tq4_dequant_fused_sdpa"])),
                ("prefill TQ4 dequant only", lambda c: median_of(c["prefill_chunk"]["tq4_dequant_only"])),
                ("prefill TQ4 rotated dequant + fused", lambda c: median_of(c["prefill_chunk"]["tq4_rotated_dequant_fused_sdpa"])),
                ("KV append 512 TQ4", lambda c: c["kv_append_chunk_ms"]["tq4_mean_last64"])]
        P("| component | " + " | ".join(f"T={T}" for T in Ts) + " |")
        P("|---|" + "---|" * len(Ts))
        for name, fn in rows:
            P(f"| {name} | " + " | ".join(f"{fn(off[T]) / mean_on(runs, lambda c, T=T: fn(c[T])):.2f}" for T in Ts) + " |")

    # ---------- 3. validation vs P475 ----------
    P("\n## 3. Instrument validation vs P475 (`Qwen3.8-27B-mlx-uniform-4bit`, N16 = `auto` + per-query verify)\n")
    P("Prefill: t(N) = f·N + 16·Σ_chunks attn(T_j) [+ 16·append per chunk for TQ4]; f fitted on the 8K rung, other rungs predicted. "
      "Decode (MTP OFF): ms/token = f_d + 16·decode(T), f_d from the 8K rung. Decode (MTP ON): round = fixed + 16·verify_k3(T); "
      "emitted/round = 1 + 2·acceptance; fixed from the 8K rung.\n")
    n16_pre = g(lambda c: median_of(c["prefill_chunk"]["native16_auto"]))
    tq_pre = g(lambda c: median_of(c["prefill_chunk"]["tq4_production"]))
    tq_app = g(lambda c: c["kv_append_chunk_ms"]["tq4_mean_last64"])
    P("| quantity | rung | measured | predicted | error |")
    P("|---|---|---|---|---|")
    for arm, pts, app in (("N16", n16_pre, None), ("TQ4", tq_pre, tq_app)):
        rungs, tps = P475["rungs"], P475["prefill_tps"][arm]
        extra = lambda N: (LAYERS * (N // CHUNK) * interp(app, N) / 1e3) if app else 0.0
        t8 = rungs[0] / tps[0]
        f = (t8 - prefill_attn_total_s(pts, rungs[0]) - extra(rungs[0])) / rungs[0]
        for N, r in zip(rungs[1:], tps[1:]):
            meas = N / r
            pred = f * N + prefill_attn_total_s(pts, N) + extra(N)
            P(f"| prefill s, {arm} | {N} | {meas:.0f} | {pred:.0f} | {100 * (pred - meas) / meas:+.1f} % |")
    tq_dec = g(lambda c: median_of(c["decode"]["tq4"]))
    rungs, tps = P475["rungs"], P475["decode_tps"]["TQ4-OFF"]
    fd = 1e3 / tps[0] - LAYERS * interp(tq_dec, rungs[0])
    for N, r in zip(rungs[1:], tps[1:]):
        meas, pred = 1e3 / r, fd + LAYERS * interp(tq_dec, N)
        P(f"| decode ms/token, TQ4 MTP OFF | {N} | {meas:.1f} | {pred:.1f} | {100 * (pred - meas) / meas:+.1f} % |")
    for arm, key in (("N16", "native16_per_query"), ("TQ4", "tq4_per_query")):
        ver = g(lambda c, key=key: median_of(c["verify"][VERIFY_K][key]))
        tps, acc = P475["decode_tps"][arm], P475["acceptance"][arm]
        e0 = 1 + 2 * acc[0]
        fixed = e0 / tps[0] * 1e3 - LAYERS * interp(ver, rungs[0])
        for N, r, a in zip(rungs[1:], tps[1:], acc[1:]):
            e = 1 + 2 * a
            pred_tps = e / (fixed + LAYERS * interp(ver, N)) * 1e3
            P(f"| decode tok/s, {arm} MTP ON | {N} | {r:.2f} | {pred_tps:.2f} | {100 * (pred_tps - r) / r:+.1f} % |")

    # ---------- 4. projections for the pick ----------
    P("\n## 4. Projections for `Qwen3.8-27B-Fable-Distill-OptiQ-4.5bpw-mixed` (vs its shipped native16 + fused_v1 + joint_v1)\n")
    P("Fixed (non-attention) cost is taken from the pick's own shipped-state measurement minus the probe's native16 attention; "
      "each TQ4 row swaps in that row's attention cost. Ceilings assume the kernel reaches the stated reference; they are "
      "upper bounds, not measurements.\n")
    fused = g(lambda c: median_of(c["prefill_chunk"]["native16_fused_v1"]))
    deqf = g(lambda c: median_of(c["prefill_chunk"]["tq4_dequant_fused_sdpa"]))
    P("### Prefill (cold, s; lower is better)\n")
    rotf = g(lambda c: median_of(c["prefill_chunk"]["tq4_rotated_dequant_fused_sdpa"]))
    P("| N | native16 shipped (measured) | TQ4 today (loop) | TQ4 dequant + fused SDPA | TQ4 rotated-space dequant + fused SDPA | TQ4 parity ceiling (fused flash at native cost) |")
    P("|---|---|---|---|---|---|")
    for N, t_meas in PICK_BASELINE["prefill_s"].items():
        f = (t_meas - prefill_attn_total_s(fused, N)) / N
        app = LAYERS * (N // CHUNK) * interp(tq_app, N) / 1e3
        today = f * N + prefill_attn_total_s(tq_pre, N) + app
        dq = f * N + prefill_attn_total_s(deqf, N) + app
        rq = f * N + prefill_attn_total_s(rotf, N) + app
        par = f * N + prefill_attn_total_s(fused, N) + app
        P(f"| {N} | {t_meas:.0f} ({N / t_meas:.0f} tok/s) | {today:.0f} ({t_meas / today:.2f}×) | {dq:.0f} ({t_meas / dq:.2f}×) | "
          f"{rq:.0f} ({t_meas / rq:.2f}×) | "
          f"{par:.0f} ({t_meas / par:.2f}×) |")
    P("\n(× = speed relative to native16 shipped; KV append of TQ4 included in every TQ4 column.)\n")
    P("### Decode, MTP ON (tok/s; higher is better), verify block k = 3, emitted/round from M58\n")
    n16j = g(lambda c: median_of(c["verify"][VERIFY_K]["native16_joint"]))
    tqpq = g(lambda c: median_of(c["verify"][VERIFY_K]["tq4_per_query"]))
    rd = g(lambda c: median_of(c["decode"]["read_tq4_bytes"]))
    e = PICK_BASELINE["emitted_per_round"]
    tq_dec_c = g(lambda c: median_of(c["decode"]["tq4_contiguous"]))
    P("| T | native16 shipped (measured) | TQ4 today (per-query verify) | + multi-query verify (one TQ4 pass, shipped layout) | + no layout copy | + kernel at TQ4-bytes read ceiling |")
    P("|---|---|---|---|---|---|")
    for T, d in PICK_BASELINE["decode_on_tps"].items():
        fixed = e / d * 1e3 - LAYERS * interp(n16j, T)
        rows = [LAYERS * interp(tqpq, T), LAYERS * interp(tq_dec, T), LAYERS * interp(tq_dec_c, T),
                LAYERS * interp(rd, T)]
        vals = [e / (fixed + a) * 1e3 for a in rows]
        P(f"| {T} | {d:.2f} | " + " | ".join(f"{v:.2f} ({v / d:.2f}×)" for v in vals) + " |")
    P("\n### Decode, MTP OFF (tok/s)\n")
    n16d = g(lambda c: median_of(c["decode"]["native16"]))
    P("| T | native16 (measured) | TQ4 today | + no layout copy | + kernel at TQ4-bytes read ceiling |")
    P("|---|---|---|---|---|")
    for T, d in PICK_BASELINE["decode_off_tps"].items():
        fixed = 1e3 / d - LAYERS * interp(n16d, T)
        vals = [1e3 / (fixed + LAYERS * interp(x, T)) for x in (tq_dec, tq_dec_c, rd)]
        P(f"| {T} | {d:.2f} | " + " | ".join(f"{v:.2f} ({v / d:.2f}×)" for v in vals) + " |")


if __name__ == "__main__":
    main()
