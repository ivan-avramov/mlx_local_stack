#!/usr/bin/env python3
"""Generate benchmark/results/m72/D1D2.md from the m72_tq4_probe ``--mode mq`` JSONs (never hand-edit the output).

M72 step 1.2 D1 + D2: the fork's dev prototype (stride-aware multi-query TQ4 decode, ``dev/m72_mq_decode.py``) against
matched in-process baselines, then decode projections for Qwen3.8-27B-Fable-Distill-OptiQ-4.5bpw-mixed with the same
method as PROBE.md §4 (fixed cost = the pick's shipped measurement minus this run's native16 attention).
Usage: python benchmark/spikes/m72_mq_report.py <run_dir> > benchmark/results/m72/D1D2.md
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from m72_probe_report import LAYERS, PICK_BASELINE, VERIFY_K, interp  # noqa: E402

PASSES = ("mq-1", "mq-2")


def main():
    d = Path(sys.argv[1])
    runs = {n: json.loads((d / f"{n}.json").read_text()) for n in PASSES if (d / f"{n}.json").exists()}
    names = list(runs)
    cks = {n: {c["T"]: c for c in runs[n]["checkpoints"]} for n in names}
    Ts = sorted(cks[names[0]])
    Tp = [T for T in Ts if T < 262144]  # sub-cap only (served layout); the cap is contiguous
    ks = sorted(cks[names[0]][Ts[0]]["mq"], key=int)

    def mean(get, T):
        return sum(get(cks[n][T]) for n in names) / len(names)

    def t(T, k, key):
        return mean(lambda c: c["mq"][k][key]["median_ms"], T)

    P = print
    m = runs[names[0]]["meta"]
    P("# M72 step 1.2 D1 + D2 — stride-aware multi-query TQ4 decode prototype (GENERATED by "
      "`benchmark/spikes/m72_mq_report.py`; never hand-edit)\n")
    P(f"MLX {m['mlx']}, {m['device']['device_name']} `{m['device']['architecture']}`; fork `{m['fork'].get('head', '?')[:8]}`"
      f" (dirty: {', '.join(m['fork'].get('dirty_paths') or []) or 'none'}); per full-attention layer, 24 q / 4 kv heads, "
      f"head dim 256, bf16, synthetic K/V, cache preallocated to 262,144 tokens; medians; mean of passes {', '.join(names)}."
      " Prototype: `dev/m72_mq_decode.py` (G = heads per simdgroup; G = 2 is the shipped singleton's grouping).\n")

    P("## 1. Exactness (per query, bit-identical to the production singleton path)\n")
    for n in names:
        ex = runs[n]["meta"]["mq_exactness"]
        multi = sum(r["classes"] > 1 for r in ex["rows"])
        P(f"- {n}: sweep {ex['n_bit_identical']} / {ex['n']} bit-identical (T ∈ {sorted({r['T'] for r in ex['rows']})}, "
          f"k = 1–5, G ∈ {{2, 1}}; {multi} cases straddle a (Blocks, tpb) class boundary → 2 launches); "
          f"negative controls (must be False): shifted lengths {ex['negative_controls']['shifted_lengths_bit_identical']}, "
          f"joint TQ path {ex['negative_controls']['joint_tq_path_bit_identical']}.")
        bad = [(T, k, G) for T in Ts for k in ks for G in (2, 1) if not cks[n][T]["mq"][k][f"mq_g{G}_bit_identical"]]
        P(f"  Checkpoints: {'all bit-identical' if not bad else f'NOT bit-identical at {bad}'}.")

    P("\n## 2. Per-layer times (ms)\n")
    P("k = 1 is plain decode (D2 alone); k ≥ 2 is an MTP verify block (D1 + D2). Production TQ4 = the shipped singleton "
      "(k ≥ 2: the per-query loop). Native16 = SDPA (k = 1) / `joint_v1`'s joint call (k ≥ 2), the shipped pick's path.\n")
    P("| T | k | native16 | TQ4 production | prototype G=2 | prototype G=1 | best / production | best / native16 | best eff. GB/s | TQ4-bytes read ceiling |")
    P("|---|---|---|---|---|---|---|---|---|---|")
    best = {}
    for T in Ts:
        rd = mean(lambda c: c["read_tq4_bytes"]["median_ms"], T)
        b = cks[names[0]][T]["bytes"]["tq4_kv"]
        for k in ks:
            n16 = t(T, k, "native16" if k == "1" else "native16_joint")
            prod = t(T, k, "tq4_production")
            g2, g1 = t(T, k, "mq_g2"), t(T, k, "mq_g1")
            bv, bg = min((g2, 2), (g1, 1))
            best[(T, k)] = bv
            P(f"| {T} | {k} | {n16:.3f} | {prod:.3f} | {g2:.3f} | {g1:.3f} | {bv / prod:.2f} (G={bg}) | {bv / n16:.2f} | "
              f"{b / bv / 1e6:.0f} | {rd:.3f} |")
    if len(names) == 2:
        P("\nPass-to-pass drift (mq-2 / mq-1, prototype G=2 at k = 1 / 3): " + ", ".join(
            f"T={T} {cks[names[1]][T]['mq']['1']['mq_g2']['median_ms'] / cks[names[0]][T]['mq']['1']['mq_g2']['median_ms']:.3f}"
            f" / {cks[names[1]][T]['mq'][VERIFY_K]['mq_g2']['median_ms'] / cks[names[0]][T]['mq'][VERIFY_K]['mq_g2']['median_ms']:.3f}"
            for T in Ts))
    P("\nPower / peak per checkpoint (first pass): " + "; ".join(
        f"T={T} {cks[names[0]][T]['power']['wattage']} {cks[names[0]][T]['power']['battery']} peak "
        f"{cks[names[0]][T]['peak_GB']:.1f} GB" for T in Ts))

    P("\n## 3. Projection for `Qwen3.8-27B-Fable-Distill-OptiQ-4.5bpw-mixed` (vs its shipped native16 + fused_v1 + joint_v1)\n")
    P("Method of PROBE.md §4 with this run's matched times: fixed = the pick's measured round (MTP ON) or token (MTP OFF) "
      "minus 16 × this run's native16 attention; each TQ4 column swaps in 16 × its attention. PROBE.md's validation puts MTP "
      "ON projections +7…+18 % optimistic (both formats, TQ4 more) and MTP OFF within −5…−8 %. Prefill unchanged by D1 + D2.\n")
    g = lambda T, k, key: interp({x: t(x, k, key) for x in Tp}, T)
    gb = lambda T, k: interp({x: best[(x, k)] for x in Tp}, T)
    e = PICK_BASELINE["emitted_per_round"]
    P(f"### Decode, MTP ON (tok/s), verify block k = {VERIFY_K}, emitted/round {e} (M58)\n")
    P("| T | native16 shipped (measured) | TQ4 today | TQ4 + prototype (D1 + D2, measured kernel) | PROBE.md estimate for D1 + D2 |")
    P("|---|---|---|---|---|")
    probe_est = {131072: 1.25, 260096: 1.51}
    for T, dd in PICK_BASELINE["decode_on_tps"].items():
        fixed = e / dd * 1e3 - LAYERS * g(T, VERIFY_K, "native16_joint")
        today = e / (fixed + LAYERS * g(T, VERIFY_K, "tq4_production")) * 1e3
        proto = e / (fixed + LAYERS * gb(T, VERIFY_K)) * 1e3
        P(f"| {T} | {dd:.2f} | {today:.2f} ({today / dd:.2f}×) | {proto:.2f} ({proto / dd:.2f}×) | {probe_est[T]:.2f}× |")
    P("\n### Decode, MTP OFF (tok/s)\n")
    P("| T | native16 (measured) | TQ4 today | TQ4 + prototype (D2, measured kernel) | PROBE.md estimate for D2 |")
    P("|---|---|---|---|---|")
    for T, dd in PICK_BASELINE["decode_off_tps"].items():
        fixed = 1e3 / dd - LAYERS * g(T, "1", "native16")
        today = 1e3 / (fixed + LAYERS * g(T, "1", "tq4_production"))
        proto = 1e3 / (fixed + LAYERS * gb(T, "1"))
        P(f"| {T} | {dd:.2f} | {today:.2f} ({today / dd:.2f}×) | {proto:.2f} ({proto / dd:.2f}×) | 1.04× |")


if __name__ == "__main__":
    main()
